    def clean_text(self, text: str) -> str:
        """
        清理文本，去除表情符号和口语化表达

        Args:
            text: 原始文本

        Returns:
            清理后的文本
        """
        # 去除表情符号
        for emoji in self.emojis:
            text = text.replace(emoji, '')

        # 去除口语化表达
        for filler in self.filler_words:
            text = text.replace(filler, '')

        # 去除多余的空格
        text = re.sub(r'\s+', ' ', text)
        text = text.strip()

        return text

